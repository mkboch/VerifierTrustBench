# ------------------------------------------------------------------ adversarial

def _clone(pairs):
    return [{"system": p["system"], "cluster": p["cluster"],
             "a": dict(p["a"]), "b": dict(p["b"])} for p in pairs]


def test_inverting_the_two_states_flips_the_sign():
    pairs = _clone(FC.eligible(CELLS, "relation", "binary", SYSTEMS))
    base = FC.pooled_diff(pairs, "balanced_accuracy_pct")
    for p in pairs:
        for side in ("a", "b"):
            p[side]["hit"], p[side]["fa"] = p[side]["fa"], p[side]["hit"]
    assert FC.pooled_diff(pairs, "balanced_accuracy_pct") == pytest.approx(-base, abs=1e-9)


def test_a_rung_compared_against_itself_is_exactly_zero():
    pairs = FC.eligible(CELLS, "binary", "binary", SYSTEMS)
    for metric in ("balanced_accuracy_pct", "dprime"):
        pt, lo, hi, _, _ = FC.cluster_bootstrap(
            pairs, lambda ps, m=metric: FC.pooled_diff(ps, m), draws=200)
        assert pt == 0 and lo == 0 and hi == 0, "a null contrast is not null"


def test_duplicating_every_relation_does_not_narrow_the_interval():
    """Relations within a cluster are not independent. If each relation were its own
    cluster, duplicating the data would shrink the interval; with the cluster as the unit
    it must not."""
    pairs = FC.eligible(CELLS, "relation", "binary", SYSTEMS)
    dup = pairs + _clone(pairs)
    f = lambda ps: FC.pooled_diff(ps, "balanced_accuracy_pct")  # noqa: E731
    p0, lo0, hi0, _, _ = FC.cluster_bootstrap(pairs, f, draws=2000)
    p1, lo1, hi1, _, _ = FC.cluster_bootstrap(dup, f, draws=2000)
    assert p1 == pytest.approx(p0, abs=1e-9)
    assert (hi1 - lo1) == pytest.approx(hi0 - lo0, abs=1e-9)


def test_dropping_data_narrows_the_eligible_set_rather_than_imputing(tmp_path):
    """Marking a response unscoreable must remove that cell from the paired set, not
    substitute a value for it.

    Only cells that are CURRENTLY eligible are counted: a cell already excluded for some
    other reason cannot be excluded twice, and an earlier version of this test got that
    arithmetic wrong and blamed the loader for it."""
    ix = {f: i for i, f in enumerate(DOC["fields"])}
    before = FC.eligible(CELLS, "relation", "binary", SYSTEMS)
    eligible_keys = {(p["system"], p["a"]["relation"]) for p in before}

    doc = json.loads(DATA.read_text())
    killed = 0
    for row in doc["cells"]:
        key = (row[ix["system"]], row[ix["relation"]])
        if (row[ix["rung"]] == "binary" and row[ix["system"]] == SYSTEMS[0]
                and key in eligible_keys and killed < 10):
            row[ix["e1_scoreable"]] = 0
            row[ix["e1_false_alarm"]] = None
            killed += 1
    assert killed == 10, "could not find ten eligible cells to invalidate"

    tmp = tmp_path / "adversarial.json"
    tmp.write_text(json.dumps(doc))
    _, cells = FC.load(tmp)
    after = FC.eligible(cells, "relation", "binary", SYSTEMS)
    assert len(after) == len(before) - killed
    assert all(p["a"]["scoreable"] and p["b"]["scoreable"] for p in after)


def test_a_smaller_sample_gives_a_wider_interval():
    pairs = FC.eligible(CELLS, "relation", "binary", SYSTEMS)
    half = [p for p in pairs if p["cluster"] <= "M10"]
    f = lambda ps: FC.pooled_diff(ps, "balanced_accuracy_pct")  # noqa: E731
    _, lo0, hi0, _, _ = FC.cluster_bootstrap(pairs, f, draws=2000)
    _, lo1, hi1, _, _ = FC.cluster_bootstrap(half, f, draws=2000)
    assert (hi1 - lo1) > (hi0 - lo0)


def test_an_unknown_system_yields_an_empty_set_rather_than_a_number():
    assert FC.eligible(CELLS, "relation", "binary", ["no_such_system"]) == []
    assert FC.pooled_diff([], "dprime") is None
    assert FC.balanced_diff([], "dprime") is None
