"""The fair-scoring analysis: the Python reference and the browser code agree, and both
behave correctly under adversarial input.

No study result is asserted anywhere in this file. The expected values below were computed
from the SYNTHETIC fixture, which is generated by a seeded random number generator, so they
are regression anchors for the software and nothing else. The study's measured outcomes are
not published in this repository.
"""
from __future__ import annotations
import json
import pathlib
import sys

import pytest

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from analysis import fair_contrasts as FC  # noqa: E402

DATA = ROOT / "docs/data/synthetic_demo_cells.json"
DOC, CELLS = FC.load(DATA)
SYSTEMS = [s["id"] for s in DOC["systems"]]

# Regression anchors computed from the synthetic fixture (seed 1104). NOT measurements.
SYNTHETIC_LADDER = {
    "blind":    {"n": 310, "hits": 43,  "false_alarms": 5},
    "category": {"n": 309, "hits": 87,  "false_alarms": 6},
    "relation": {"n": 305, "hits": 85,  "false_alarms": 18},
    "binary":   {"n": 310, "hits": 157, "false_alarms": 24},
}
SYNTHETIC_CONTRAST = {"n": 300, "point": 10.166667, "lo": 5.821918, "hi": 14.500000}


# ------------------------------------------------------------------ the estimator itself

def test_dprime_uses_the_loglinear_correction_unconditionally():
    # a middling cell still gets the correction: (h + 0.5) / (n + 1)
    assert FC.loglinear_dprime(50, 100, 10, 100) == pytest.approx(
        FC._z(50.5 / 101) - FC._z(10.5 / 101))
    # and a saturated cell stays finite instead of diverging
    assert abs(FC.loglinear_dprime(10, 10, 0, 10)) < 10


def test_balanced_accuracy_is_the_mean_of_sensitivity_and_specificity():
    a = FC.agg([{"hit": 1, "fa": 0}] * 7 + [{"hit": 0, "fa": 1}] * 3)
    assert a["sensitivity_pct"] == pytest.approx(70.0)
    assert a["false_alarm_rate_pct"] == pytest.approx(30.0)
    assert a["balanced_accuracy_pct"] == pytest.approx(70.0)


def test_z_is_the_inverse_normal_cdf():
    assert FC._z(0.5) == pytest.approx(0.0, abs=1e-12)
    assert FC._z(0.975) == pytest.approx(1.959963984540054, abs=1e-9)
    assert FC._z(0.025) == pytest.approx(-1.959963984540054, abs=1e-9)


def test_the_prng_is_reproducible():
    a = [FC.Mulberry32(20261016).next_u32() for _ in range(5)]
    b = [FC.Mulberry32(20261016).next_u32() for _ in range(5)]
    assert a == b
    assert a != [FC.Mulberry32(1).next_u32() for _ in range(5)]
    assert all(0 <= x < 2 ** 32 for x in a)


# ------------------------------------------------------------------ against the fixture

@pytest.mark.parametrize("rung", list(SYNTHETIC_LADDER))
def test_ladder_reproduces_the_synthetic_anchors(rung):
    got = FC.ladder_table(CELLS, SYSTEMS)[rung]
    for k, v in SYNTHETIC_LADDER[rung].items():
        assert got[k] == v, f"{rung}.{k}: {got[k]} != {v}"


def test_a_contrast_reproduces_its_synthetic_anchor():
    pairs = FC.eligible(CELLS, "relation", "binary", SYSTEMS)
    assert len(pairs) == SYNTHETIC_CONTRAST["n"]
    pt, lo, hi, _, _ = FC.cluster_bootstrap(
        pairs, lambda ps: FC.pooled_diff(ps, "balanced_accuracy_pct"))
    assert pt == pytest.approx(SYNTHETIC_CONTRAST["point"], abs=1e-5)
    assert lo == pytest.approx(SYNTHETIC_CONTRAST["lo"], abs=1e-5)
    assert hi == pytest.approx(SYNTHETIC_CONTRAST["hi"], abs=1e-5)


def test_every_contrast_runs_and_reports_a_complete_case_denominator():
    for a, b in FC.CONTRASTS:
        pairs = FC.eligible(CELLS, a, b, SYSTEMS)
        assert pairs, f"{a}->{b} has no eligible cells"
        for p in pairs:
            assert p["a"]["scoreable"] and p["b"]["scoreable"]
            assert p["a"]["relation"] == p["b"]["relation"]
            assert p["a"]["system"] == p["b"]["system"]


# ------------------------------------------------------------------ browser parity

def _js(draws):
    quickjs = pytest.importorskip("quickjs", reason="quickjs is needed to execute fair.js")
    ctx = quickjs.Context()
    ctx.eval((ROOT / "docs/assets/fair.js").read_text())
    ctx.set("__DATA", DATA.read_text())
    return json.loads(ctx.eval("""
    (function(){
      const doc = JSON.parse(__DATA);
      const D = VTBFair.parse(doc);
      const sys = doc.systems.map(s => s.id);
      const rows = [];
      for (const [a,b] of VTBFair.CONTRASTS)
        for (const m of ["balanced_accuracy_pct","dprime"])
          for (const w of ["pooled","system_balanced"]) {
            const r = VTBFair.contrast(D,a,b,sys,w,m,%d);
            rows.push({c:a+"->"+b, m:m, w:w, n:r.n_cells, pt:r.point, lo:r.lo, hi:r.hi,
                       z:r.excludesZero});
          }
      return JSON.stringify({ladder: VTBFair.ladderTable(D,sys), rows: rows});
    })()
    """ % draws))


def test_browser_code_matches_the_python_reference():
    """Same estimand, same PRNG, two languages. Reduced draws to stay quick; the full-draw
    comparison is the test below."""
    draws = 300
    js = _js(draws)
    for row in js["rows"]:
        a, b = row["c"].split("->")
        pairs = FC.eligible(CELLS, a, b, SYSTEMS)
        fn = FC.pooled_diff if row["w"] == "pooled" else FC.balanced_diff
        pt, lo, hi, _, _ = FC.cluster_bootstrap(
            pairs, lambda ps, m=row["m"], g=fn: g(ps, m), draws=draws)
        assert row["n"] == len(pairs)
        assert row["pt"] == pytest.approx(pt, abs=1e-9), row
        assert row["lo"] == pytest.approx(lo, abs=1e-9), row
        assert row["hi"] == pytest.approx(hi, abs=1e-9), row
        assert row["z"] == (lo > 0 or hi < 0)
    for rung, t in js["ladder"].items():
        ref = FC.ladder_table(CELLS, SYSTEMS)[rung]
        for k, v in ref.items():
            assert t[k] == pytest.approx(v, abs=1e-9), (rung, k)


